const {chromium} = require(process.env.PROJECTM_PLAYWRIGHT_MODULE);
const assert = require('node:assert/strict');

(async () => {
  const browser = await chromium.launch({executablePath: process.env.PROJECTM_CHROME, headless: true});
  try {
    const page = await browser.newPage({viewport: {width: 1200, height: 1100}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.argv[2] + '/#projectm');
    await page.locator('#projectm-panel').waitFor({state: 'visible'});
    await page.waitForFunction(() => !document.getElementById('projectm-start').disabled);
    const presets = await page.evaluate(async () => (await (await fetch('/api/projectm/presets')).json()).presets);
    assert.ok(presets.length > 250);
    await page.waitForFunction(count => document.querySelectorAll('#projectm-preset option').length === count, presets.length);
    assert.deepEqual(await page.locator('#projectm-preset option').evaluateAll(options => options.map(option => ({id: Number(option.value), name: option.textContent}))), presets);
    await page.locator('#projectm-start').click();
    await page.waitForFunction(() => document.getElementById('projectm-status').textContent.includes('Live'));
    await page.locator('#projectm-search').fill('Library');
    const matches = presets.filter(preset => preset.name.includes('Library'));
    await page.waitForFunction(count => document.querySelectorAll('#projectm-preset option').length === count + 1, matches.length);
    assert.deepEqual(await page.locator('#projectm-preset option').evaluateAll(options => options.filter(option => option.textContent.includes('Library')).map(option => Number(option.value))), matches.map(preset => preset.id));
    const lastMatch = matches.at(-1);
    await page.locator('#projectm-preset').selectOption(String(lastMatch.id));
    await page.waitForFunction(name => document.getElementById('projectm-now').textContent.includes(name), lastMatch.name);
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-search').fill('');
    await page.waitForFunction(count => document.querySelectorAll('#projectm-preset option').length === count, presets.length);
    await page.locator('#projectm-search').fill('Waves');
    await page.waitForFunction(() => document.querySelectorAll('#projectm-preset option').length <= 2);
    await page.locator('#projectm-preset').selectOption({label: 'Waves'});
    await page.waitForFunction(() => document.getElementById('projectm-now').textContent.includes('Waves'));
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-auto').uncheck();
    await page.waitForFunction(async () => !(await (await fetch('/api/state')).json()).projectm.auto);
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-favorite').click();
    await page.waitForFunction(() => document.querySelectorAll('#projectm-favorites button').length === 1);
    assert.equal(await page.locator('#projectm-favorite').getAttribute('aria-pressed'), 'true');
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-next').click();
    await page.waitForFunction(() => document.getElementById('projectm-now').textContent.includes('Fractal'));
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-favorite').click();
    await page.waitForFunction(() => document.querySelectorAll('#projectm-favorites button').length === 2);
    await page.reload();
    await page.locator('#projectm-favorites button').filter({hasText: 'Waves'}).waitFor();
    assert.equal(await page.locator('#projectm-favorites button').count(), 2);
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-auto').check();
    await page.waitForFunction(async () => (await (await fetch('/api/state')).json()).projectm.auto);
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-search').fill('Fractal');
    await page.locator('#projectm-favorites button').filter({hasText: 'Waves'}).click();
    await page.waitForFunction(() => document.getElementById('projectm-now').textContent.includes('Waves') && !document.getElementById('projectm-auto').checked);
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-favorite').click();
    await page.waitForFunction(() => document.querySelectorAll('#projectm-favorites button').length === 1);
    assert.equal(await page.locator('#projectm-favorite').getAttribute('aria-pressed'), 'false');
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-favorites button').filter({hasText: 'Fractal'}).click();
    await page.waitForFunction(() => document.getElementById('projectm-now').textContent.includes('Fractal'));
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-favorite').click();
    await page.locator('#projectm-favorites-empty').waitFor({state: 'visible'});
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-auto').check();
    await page.waitForFunction(async () => (await (await fetch('/api/state')).json()).projectm.auto);
    await page.waitForFunction(() => !document.getElementById('projectm-controls').disabled);
    await page.locator('#projectm-randomize').click();
    await page.waitForFunction(() => !document.getElementById('projectm-auto').checked);
    const randomized = await page.evaluate(async () => (await (await fetch('/api/state')).json()).projectm);
    assert.equal(randomized.active, true);
    assert.equal(randomized.auto, false);
    assert.equal(await page.locator('#projectm-preset').inputValue(), String(randomized.preset));
    assert.ok((await page.locator('#projectm-now').textContent()).includes(randomized.name));
    await page.waitForFunction(() => document.getElementById('projectm-preview').getContext('2d').getImageData(1, 1, 1, 1).data[0] > 0);
    await page.locator('#audio-tab').click();
    assert.equal(await page.evaluate(async () => (await (await fetch('/api/state')).json()).projectm.active), true);
    await page.locator('#projectm-tab').click();
    await page.locator('#projectm-stop').click();
    await page.locator('#audio-panel').waitFor({state: 'visible'});
    assert.equal(await page.evaluate(async () => (await (await fetch('/api/state')).json()).projectm.active), false);
    assert.deepEqual(errors, []);
    console.log('projectM tab: full list, search, favorites, reload, playback, auto, randomize, preview, browsing, stop passed');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
